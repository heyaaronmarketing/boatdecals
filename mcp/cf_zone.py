"""Apply the zone-level settings the SEO/AEO playbook calls for, and read them back.

Wrangler's OAuth token is zone:read only, which is why this is a separate
script with its own token: these are account-level writes and they want a
deliberate, scoped credential rather than the one that happens to be sitting
in a deploy config.

    python3 mcp/cf_zone.py                 # read every setting, change nothing
    python3 mcp/cf_zone.py --apply         # write the ones that are wrong

The token needs Zone:Zone Settings:Edit and Zone:Zone:Read on this zone only.
Put it in ~/.cf-zone-token (chmod 600) or CF_ZONE_TOKEN - never on the command
line, where it lands in shell history.

Nothing here touches DNS, firewall, Bot Fight Mode or the AI-scraper toggles.
Those change who can reach the site, and on a site whose whole strategy is
being readable by answer engines that is a decision, not a setting. (Verified
2026-11-14: all seven major crawlers get 200 with full content. Leave it.)
"""
import json, os, sys, urllib.request, urllib.error

ZONE_NAME = "numbermyboat.com"
API = "https://api.cloudflare.com/client/v4"

# setting id -> (value, why)
WANT = {
    "ssl": ("full",
            "the origin is a Worker behind Cloudflare's own certificate; "
            "Flexible would serve the site over plaintext on the back half"),
    "min_tls_version": ("1.2",
                        "1.0 and 1.1 are deprecated and fail PCI; nothing "
                        "that orders a boat decal is on a 2013 browser"),
    "always_use_https": ("on",
                         "one scheme, one canonical URL - http and https "
                         "answering separately is a duplicate-content bug"),
    "automatic_https_rewrites": ("on",
                                 "rewrites stray http:// subresources rather "
                                 "than letting them become mixed content"),
    "early_hints": ("on",
                    "Cloudflare sends 103 with the stylesheet link before the "
                    "Worker has finished - measurable LCP win, zero code"),
    "brotli": ("on", "smaller than gzip on text, and the site is all text"),
    "browser_cache_ttl": (86400,
                          "the HTML is regenerated by a build, not per "
                          "request; a day is honest and the pages carry their "
                          "own cache headers where they need to differ"),
    "rocket_loader": ("off",
                      "it defers and reorders inline scripts. The order form "
                      "IS inline script, and a reordered pricing IIFE is a "
                      "wrong price on the button"),
}

# Written through its own endpoint shape (a dict value, not a scalar), and in
# TWO WRITES, which is not optional.
#
# Cloudflare rejects the whole payload with a bare "1051 Invalid value for zone
# setting" if preload:true arrives while HSTS is still disabled. The error names
# no field, so the only way to find it was to send the fields one at a time
# against the live zone: everything passed up to and including nosniff, and the
# full payload then passed too - because by that point HSTS was already on.
# Enable first, then ask for preload.
HSTS_ON = {
    "enabled": True,
    "max_age": 31536000,          # one year
    "include_subdomains": True,
    "nosniff": True,
}
HSTS_PRELOAD = dict(HSTS_ON, preload=True)
HSTS_WHY = ("a year of HSTS with preload means the first request of a return "
            "visit is never plaintext. Note it is hard to undo - a browser "
            "that has seen the header refuses http for a year, and switching "
            "the setting back off does not release the browsers that already "
            "have it")


def token():
    t = os.environ.get("CF_ZONE_TOKEN")
    if t:
        return t.strip()
    p = os.path.expanduser("~/.cf-zone-token")
    if os.path.exists(p):
        return open(p).read().strip()
    sys.exit("No token. Put one in ~/.cf-zone-token (chmod 600) or "
             "CF_ZONE_TOKEN. It needs Zone Settings:Edit on " + ZONE_NAME)


def api(path, method="GET", body=None):
    req = urllib.request.Request(
        API + path,
        data=json.dumps(body).encode() if body is not None else None,
        method=method,
        headers={"Authorization": "Bearer " + token(),
                 "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            return json.load(r)
    except urllib.error.HTTPError as e:
        return json.load(e)


def zone_id():
    j = api("/zones?name=" + ZONE_NAME)
    if not j.get("success"):
        sys.exit("zone lookup failed: %s" % json.dumps(j.get("errors"))[:300])
    res = j.get("result") or []
    if not res:
        sys.exit("no zone named %s on this token's account" % ZONE_NAME)
    return res[0]["id"]


def main():
    apply_ = "--apply" in sys.argv
    zid = zone_id()
    print("zone %s  %s\n" % (ZONE_NAME, zid))
    changed = failed = 0

    for sid, (want, why) in WANT.items():
        cur = api("/zones/%s/settings/%s" % (zid, sid))
        now = (cur.get("result") or {}).get("value")
        editable = (cur.get("result") or {}).get("editable", True)
        ok = str(now) == str(want)
        print("%-26s now=%-10s want=%-10s %s"
              % (sid, now, want, "OK" if ok else
                 ("not editable on this plan" if not editable else "WRONG")))
        if ok or not editable:
            continue
        if not apply_:
            print("    why: %s" % why)
            continue
        r = api("/zones/%s/settings/%s" % (zid, sid), "PATCH", {"value": want})
        if r.get("success"):
            print("    set -> %s" % ((r.get("result") or {}).get("value")))
            changed += 1
        else:
            print("    FAILED: %s" % json.dumps(r.get("errors"))[:200])
            failed += 1

    path = "/zones/%s/settings/security_header" % zid
    cur = api(path)
    now = (((cur.get("result") or {}).get("value") or {})
           .get("strict_transport_security") or {})
    ok = (bool(now.get("enabled")) and now.get("max_age", 0) >= 31536000
          and now.get("include_subdomains") and now.get("preload")
          and now.get("nosniff"))
    print("\n%-26s now=%s" % ("security_header (HSTS)", json.dumps(now)))
    if ok:
        print("  OK")
    elif not apply_:
        print("  WRONG\n    why: %s" % HSTS_WHY)
    else:
        last = None
        for step, label in ((HSTS_ON, "enabled"), (HSTS_PRELOAD, "preload")):
            last = api(path, "PATCH",
                       {"value": {"strict_transport_security": step}})
            if not last.get("success"):
                print("  FAILED at %s: %s"
                      % (label, json.dumps(last.get("errors"))[:200]))
                failed += 1
                break
        else:
            print("  set -> %s"
                  % json.dumps(((last.get("result") or {}).get("value") or {})
                               .get("strict_transport_security")))
            changed += 1

    print("\nAuto Minify is not listed: Cloudflare removed it in August 2024. "
          "\nThe build already ships minified CSS and JS.")
    if not apply_:
        print("\nRead-only. Re-run with --apply to write the WRONG ones.")
    else:
        print("\n%d changed, %d failed." % (changed, failed))
        if failed:
            sys.exit(1)


if __name__ == "__main__":
    main()
