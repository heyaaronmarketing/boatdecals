#!/usr/bin/env python3
"""Emit the registration and HIN tables as a JS module.

Same arrangement as build_gates_js.py and for the same reason: the tables have
exactly one definition, in engine/content.py and engine/tools.py, and they are
emitted here rather than retyped. The 56 vessel prefixes, the nine postal-code
confusions, Maine's format exception, California's unissued letters and the
MIC table are all Python data; worker/decode.js is the one piece of logic that
reads them, and both the website and the MCP server run that same file.

Run: python3 mcp/build_decode_js.py
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "engine"))

DEST = ROOT / "worker" / "decode-data.js"


def main():
    import content as C
    import tools as T

    data = {
        "PREFIX_STATE": C.PREFIX_STATE,
        "NO_LETTERS": C.NO_LETTERS,
        # Flattened: JS has no tuples, and {state, prefix} reads better than [0]/[1].
        "POSTAL_MISTAKE": {k: {"state": v[0], "prefix": v[1]}
                           for k, v in C.POSTAL_MISTAKE.items()},
        "FORMAT_EXCEPTIONS": C.FORMAT_EXCEPTIONS,
        "MIC": T.MIC,
    }
    DEST.write_text(
        "// GENERATED by mcp/build_decode_js.py - do not edit.\n"
        "//\n"
        "// Tables only. The logic that reads them is worker/decode.js, which\n"
        "// the website and the MCP server both run - one implementation, not\n"
        "// two held together by a test.\n"
        "export const T = " + json.dumps(data, indent=0, sort_keys=True)
        + ";\n", encoding="utf-8")
    print("-> %s  (%.0f KB)" % (DEST, DEST.stat().st_size / 1024))
    print("   %d prefixes, %d postal confusions, %d format exceptions, "
          "%d MIC codes" % (len(data["PREFIX_STATE"]),
                            len(data["POSTAL_MISTAKE"]),
                            len(data["FORMAT_EXCEPTIONS"]), len(data["MIC"])))


if __name__ == "__main__":
    main()
