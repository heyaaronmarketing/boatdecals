#!/usr/bin/env python3
"""Bake real per-character font metrics for the fit gate.

WHY THIS EXISTS. The site's browser estimate is `chars * 2.5" + spaces * 1.5"`
at a fixed 4 inches, with no idea which face is selected. Playbill at 4 inches
and Arial Bold at 4 inches are not the same width, and a customer measuring
his transom against that number is measuring against a guess.

The real widths are in the ten TTFs, and those live in R2 - two are in this
repo, eight are not. But the worker already serves /api/outline, which loads
the actual font file and reports `advance` (the real advance width in font
units), `upm` and `capRatio`. So the metrics are MEASURED from the same files
that cut the vinyl, pulled once, and committed.

Derived and committed, the same pattern as the name bank and the lexicon: the
generator is in the repo, the artefact is what the gate reads, and the gate
never needs the network.

Run: python3 mcp/build_font_metrics.py          (uses the live site)
     python3 mcp/build_font_metrics.py --check  (re-validate, no rewrite)
"""
import json
import pathlib
import sys
import time
import urllib.parse
import urllib.request

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "engine"))

DEST = HERE / "data" / "font_metrics.json"
API = "https://numbermyboat.com/api/outline"

# Exactly the set worker/outline.js accepts. Measuring anything else would
# produce a table the renderer cannot honour.
CHARSET = ("ABCDEFGHIJKLMNOPQRSTUVWXYZ"
           "abcdefghijklmnopqrstuvwxyz"
           "0123456789"
           " .,'&!?@#:/()+-")


def fetch(text, fonts):
    q = urllib.parse.urlencode({"t": text, "f": ",".join(fonts)})
    req = urllib.request.Request(API + "?" + q,
                                 headers={"User-Agent": "numbermyboat-build"})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=30) as r:
                return json.loads(r.read().decode("utf-8"))
        except Exception as e:
            if attempt == 3:
                raise
            time.sleep(1.5 * (attempt + 1))


def main():
    from content import FONTS
    labels = [f[0] for f in FONTS]
    check_only = "--check" in sys.argv

    if check_only:
        if not DEST.exists():
            sys.exit("no %s to check" % DEST)
        data = json.loads(DEST.read_text())
    else:
        data = {"note": "Generated by mcp/build_font_metrics.py from the live "
                        "/api/outline, which measures the actual TTFs in R2. "
                        "Do not edit.",
                "source": API,
                "fonts": {}}
        # One call per character carrying all ten faces: the API takes up to 12
        # fonts at once, so this is 78 requests rather than 780.
        # The space has to be measured by difference: /api/outline trims its
        # input, so t=" " is an empty request and the API rightly 400s. "H H"
        # minus "HH" is the space's advance, and it is the only character that
        # needs the trick.
        pairs = fetch("HH", labels)
        gapped = fetch("H H", labels)
        for label in labels:
            a = (pairs["fonts"].get(label) or {}).get("advance")
            b = (gapped["fonts"].get(label) or {}).get("advance")
            if a is None or b is None:
                sys.exit("could not measure the space in %r" % label)
            m = pairs["fonts"][label]
            data["fonts"].setdefault(
                label, {"upm": m["upm"], "cap_ratio": m["capRatio"],
                        "advance": {}})["advance"][" "] = b - a

        for i, ch in enumerate(CHARSET):
            if ch == " ":
                continue
            d = fetch(ch, labels)
            if not d.get("ok"):
                sys.exit("api refused %r: %s - the fit gate cannot ship a "
                         "table with a hole in it" % (ch, d.get("error")))
            for label in labels:
                m = d["fonts"].get(label) or {}
                if "error" in m:
                    sys.exit("font %r could not be measured: %s - the fit gate "
                             "must not ship a table with a hole in it"
                             % (label, m["error"]))
                f = data["fonts"].setdefault(
                    label, {"upm": m["upm"], "cap_ratio": m["capRatio"],
                            "advance": {}})
                f["advance"][ch] = m["advance"]
            if (i + 1) % 20 == 0:
                print("  measured %d of %d characters" % (i + 1, len(CHARSET)))
        DEST.parent.mkdir(exist_ok=True)
        DEST.write_text(json.dumps(data, indent=0, sort_keys=True))
        print("-> %s  (%.0f KB)" % (DEST, DEST.stat().st_size / 1024))

    # --- validate the model against whole strings ------------------------
    # Summing per-character advances ignores kerning. Rather than assume that
    # is negligible, measure it: ask the API for the advance of a whole name
    # and compare. If a face kerns hard, the gate must know by how much.
    bank = json.loads((HERE / "data" / "name_bank.json").read_text())
    sample = [n["name"] for n in bank["names"]
              if all(c in CHARSET for c in n["name"])][::37][:24]
    worst = {}
    for name in sample:
        d = fetch(name[:60], labels)
        for label in labels:
            got = (d["fonts"].get(label) or {}).get("advance")
            if got is None:
                continue
            f = data["fonts"][label]
            pred = sum(f["advance"].get(c, 0) for c in name[:60])
            if got:
                err = abs(pred - got) / got
                if err > worst.get(label, (0, ""))[0]:
                    worst[label] = (err, name)
    print()
    print("kerning error, predicted vs measured, worst case per face:")
    for label in labels:
        e, nm = worst.get(label, (0.0, "-"))
        print("  %-20s %5.2f%%   (%s)" % (label, e * 100, nm))
    mx = max((e for e, _ in worst.values()), default=0.0)
    print()
    print("worst face: %.2f%% - the fit gate reports this as its own error bar"
          % (mx * 100))
    return 0


if __name__ == "__main__":
    sys.exit(main())
