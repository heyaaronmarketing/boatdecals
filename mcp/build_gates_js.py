#!/usr/bin/env python3
"""Emit the gates' data tables as a JS module for the worker.

THE ARCHITECTURAL PROBLEM, STATED PLAINLY. The MCP server has to be reachable
over HTTPS by Claude's directory and by ChatGPT, so it runs on the Cloudflare
Worker that already serves this site - which means JavaScript. The gates were
written in Python, where the 1,089-name validation corpus lives.

The spec's hardest rule is one implementation. Two copies of the gates is not
one implementation, and pretending otherwise would be the exact failure the
rule exists to prevent: an assistant telling a customer his name is clear on
the radio while the site's own tool calls it a mouthful.

So the split is deliberate and narrow:

  DATA   lives here, in Python, and is EMITTED into worker/gates-data.js.
         Every table - the rebus tokens, the homophones, the respelling rules,
         the archaic collisions, the overuse tiers, the font metrics - has one
         definition. A table cannot drift because there is only one of it.

  LOGIC  exists twice: ~150 lines in mcp/gates.py and the same in
         worker/gates.js. This is the real cost, and it is paid for by
         mcp/test_equivalence.py, which runs BOTH implementations over all
         1,089 bank names plus fixtures and fails the build on any
         disagreement. Not a spot check - every name, every field.

  LEXICON is 509 KB gzipped and lives in R2, loaded once per isolate and
         cached in module scope, the same proven pattern as the ten fonts.

Run: python3 mcp/build_gates_js.py
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
import gates as G  # noqa: E402

DEST = ROOT / "worker" / "gates-data.js"


def js_regex_rules():
    """Python (pattern, replacement) -> JS [source, flags, replacement].

    Two differences that would silently change verdicts if ignored:
    re.sub replaces EVERY occurrence, so the JS needs the /g flag; and a
    Python backreference is \\1 where JS wants $1.
    """
    out = []
    for pat, repl in G.RESPELL_RULES:
        anchored = pat.endswith("$") or pat.startswith("^")
        out.append([pat, "" if anchored else "g",
                    repl.replace("\\1", "$1")])
    return out


def main():
    met = json.loads((HERE / "data" / "font_metrics.json").read_text())
    data = {
        "REBUS_TOKENS": sorted(G.REBUS_TOKENS),
        "VISUAL_ONLY": "".join(sorted(G.VISUAL_ONLY)),
        "HOMOPHONES": G.HOMOPHONES,
        "ARCHAIC_COLLISIONS": sorted(G.ARCHAIC_COLLISIONS),
        "RESPELL_RULES": js_regex_rules(),
        "OVERUSE_T1": sorted(G.OVERUSE_T1),
        "OVERUSE_T2": sorted(G.OVERUSE_T2),
        "FORBIDDEN_CLAIMS": list(G._FORBIDDEN_CLAIMS),
        "FIT_ERROR_PCT": G.FIT_ERROR_PCT,
        "HEIGHTS_IN": list(G.HEIGHTS_IN),
        "COMFORT": G.COMFORT,
        "FONTS": met["fonts"],
    }
    body = json.dumps(data, indent=0, sort_keys=True)
    DEST.write_text(
        "// GENERATED by mcp/build_gates_js.py - do not edit.\n"
        "//\n"
        "// Every table here has exactly one definition, in mcp/gates.py. The\n"
        "// gate logic exists in both languages and is held together by\n"
        "// mcp/test_equivalence.py, which compares the two over all 1,089\n"
        "// bank names on every build.\n"
        "export const D = " + body + ";\n", encoding="utf-8")
    print("-> %s  (%.0f KB)" % (DEST, DEST.stat().st_size / 1024))
    print("   %d rebus tokens, %d homophones, %d respell rules, "
          "%d archaic, %d tier-1, %d faces"
          % (len(data["REBUS_TOKENS"]), len(data["HOMOPHONES"]),
             len(data["RESPELL_RULES"]), len(data["ARCHAIC_COLLISIONS"]),
             len(data["OVERUSE_T1"]), len(data["FONTS"])))


if __name__ == "__main__":
    main()
