#!/usr/bin/env python3
"""Emit the price table as a JS module for the worker and the order form.

WHY THIS FILE EXISTS. Before it, the price lived in two places that had to be
hand-kept in step: `PRICE` in engine/content.py, which builds every page, and
`BASE`/`HEIGHT_ADD`/`OUTLINE_ADD` in worker/index.js, which takes the money.
verify.py had a gate comparing them, and the gate worked - but a gate that
compares two copies is a smoke alarm, not a fix. The copies still existed, and
the November undercharge bug (a bundle quoted at the registration-number base)
was a third copy of the same information in a third vocabulary.

So: ONE table, in Python, where the pages are built - emitted here into
worker/price-data.js, which worker/price.js imports and which engine/
shared_js.py inlines into the browser. The order form's running total, the
Stripe intent, /api/price, the MCP quote and the printed page all read the
same numbers through the same function.

The derived file is committed, like worker/gates-data.js and
worker/decode-data.js: the Worker runtime cannot run Python, and a build step
that must succeed before a deploy is a build step that will one day not have
run. verify.py regenerates this file and fails on any diff, so the committed
copy cannot go stale.

Run: python3 mcp/build_price_js.py
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "engine"))

from content import PRICE, UPGRADES          # noqa: E402

DEST = ROOT / "worker" / "price-data.js"


def table():
    """Exactly what the pricing function needs, and nothing else.

    Deliberately NOT the whole PRICE dict. market_low/market_high are claims
    about other shops' prices used in prose; shipping it to the pricing
    function would invite someone to price against it.
    """
    return {
        "NUMBERS": PRICE["numbers"],
        "HEIGHT_ADD": PRICE["height_add"],
        "NAME_BANDS": PRICE["name_bands"],
        "BUNDLE_OFF": PRICE["bundle_off"],
        "OUTLINE_ADD": PRICE["outline"],
        # Keyed by the label the form posts. The upgrade list and its prices
        # have one definition, in content.UPGRADES.
        "UPGRADE_ADD": {u[0]: u[1] for u in UPGRADES},
        # The floor and ceiling are sanity rails, not prices. The floor is the
        # cheapest thing we sell, so a bug that drops every component still
        # cannot charge less than a real order.
        "MIN": PRICE["numbers"],
        "MAX": 200,
        # Published shorthands, carried so the form and the MCP tool can show
        # "from $X" without a second copy of the number.
        "FROM": {
            "numbers": PRICE["numbers"],
            "name": PRICE["name_from"],
            "bundle": PRICE["bundle_from"],
        },
    }


def main():
    body = json.dumps(table(), indent=1, sort_keys=True, ensure_ascii=False)
    DEST.write_text(
        "// GENERATED by mcp/build_price_js.py from engine/content.py PRICE.\n"
        "// Do not edit. Change the price in engine/content.py and re-run:\n"
        "//     python3 mcp/build_price_js.py\n"
        "// verify.py regenerates this file and fails the build on any diff,\n"
        "// so an edit here would be reverted by the next build anyway.\n"
        "export const P = " + body + ";\n", encoding="utf-8")
    t = table()
    print("-> %s  (%.1f KB)" % (DEST, DEST.stat().st_size / 1024))
    print("   numbers $%d  heights %s  bands %s  bundle -$%d  outline +$%d"
          % (t["NUMBERS"],
             "/".join("%s:+%d" % (h, a) for h, a in sorted(t["HEIGHT_ADD"].items())),
             "/".join("%s:$%d" % (b["key"], b["price"]) for b in t["NAME_BANDS"]),
             t["BUNDLE_OFF"], t["OUTLINE_ADD"]))


if __name__ == "__main__":
    main()
