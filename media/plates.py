#!/usr/bin/env python3
"""Clean hull plates for the live order preview, and their calibration.

    python3 media/plates.py            # crop + resize + print the calibration

These four shots (PV-01..PV-04, generated by gen.py) are the only images on the
site with NO lettering on them. Every other hull photo was generated with a
registration number already applied, so the order form cannot draw the
customer's own text onto one without it doubling up.

What a plate has to be, for live text to sit on it believably:

  * square-on. The rub rail in PV-01 is level to within 6px across 1400, so the
    lettering plane is fronto-parallel and a plain 2D transform is enough -
    no homography, nothing to peel off a curve.
  * cropped tight. This is the one that is easy to get wrong. On the full
    PV-01 frame the hull spans about 13 feet, so a 3" character renders 29px
    tall on the master and about 15px at the panel's real display width -
    true to scale and illegible. Cropping the side plates to roughly six feet
    of hull doubles that without telling a single lie about proportion.

CALIBRATION

`inches` is the one number that makes the preview honest: how much real hull
the plate's WIDTH spans. Everything else is derived from it - pixels per inch,
and from that the height of a 3" character. The boats are not real, so no
dimension here is measured; each is declared from the hull geometry in the
frame (rub rail to waterline on the side plates, corner to corner on the
transoms) against normal dimensions for a boat that size. The order form
prints the matching `nominal` on screen, so the assumption is visible to the
customer rather than implied.
"""
import json, pathlib, shutil, subprocess, sys

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent
SRC = ROOT / "shots"
OUT = ROOT.parent / "public" / "assets" / "img"
CWEBP = shutil.which("cwebp")
WIDTHS = [800, 1400]

# crop = (left, top, width, height) in master pixels; None keeps the full frame.
PLATES = [
    {
        "id": "PV-01", "view": "side", "dark": False,
        # Bow is to the RIGHT on this plate. The crop ends at x=1400, where the
        # keel has swept up into the stem, so the bow curve stays in frame -
        # without it the plate reads as a white wall rather than a boat. The
        # lettering then sits forward of midships, which is where 33 CFR 173.27
        # requires it, on hull still flat enough for a plane transform.
        "crop": (680, 160, 720, 480),
        # Rub rail measured at master y=321 (level to 6px across the frame).
        # Topside rail-to-keel is 299px; declared 30in for a 17ft runabout,
        # giving 9.97 px/in, so the 720px crop spans 72in of hull.
        "inches": 72,
        "anchor": [0.12, 0.40],    # left edge / top of the lettering
        "align": "left",
        "deg": 0,
        "nominal": "17 ft runabout",
    },
    {
        "id": "PV-02", "view": "side", "dark": True,
        "crop": (150, 120, 1020, 680),
        # Rail runs master y=223 at x=200 to y=251 at x=1400 - 1.3 degrees.
        # Navy topside averages 480px; declared 34in at the bow, 14.1 px/in,
        # so the 1020px crop spans 72in.
        "inches": 72,
        # Bow is to the LEFT here, so forward is the left of the frame - but
        # not hard against it, which is the stem curve.
        "anchor": [0.18, 0.21],
        "align": "left",
        "deg": 1.0,
        "nominal": "19 ft bowrider",
    },
    {
        "id": "PV-03", "view": "transom", "dark": False,
        "crop": None,
        # Transom face spans 1465px corner to corner; declared 78in, which is
        # normal for a boat this size, giving 18.8 px/in across an 82in frame.
        "inches": 82,
        "anchor": [0.50, 0.33],
        "align": "center",
        "deg": 0,
        "nominal": "78 in transom",
    },
    {
        "id": "PV-04", "view": "transom", "dark": True,
        "crop": None,
        # Face spans 1335px; same declared 78in, 17.1 px/in, 90in frame.
        "inches": 90,
        "anchor": [0.50, 0.30],
        "align": "center",
        "deg": 0,
        "nominal": "78 in transom",
    },
]


def build(plate):
    src = SRC / (plate["id"] + ".jpg")
    if not src.exists():
        sys.exit("missing master %s - run: python3 media/gen.py --only %s"
                 % (src, plate["id"]))
    im = Image.open(src)
    if plate["crop"]:
        l, t, w, h = plate["crop"]
        im = im.crop((l, t, l + w, t + h))
    master = OUT / (plate["id"] + "-crop.jpg")
    im.save(master, quality=92)
    for w in WIDTHS:
        jpg = OUT / ("%s-%d.jpg" % (plate["id"], w))
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(master),
                        "-vf", "scale=%d:-2:flags=lanczos" % w, "-q:v", "4",
                        "-frames:v", "1", str(jpg)], check=True)
        if CWEBP:
            subprocess.run([CWEBP, "-quiet", "-q", "82", str(jpg), "-o",
                            str(OUT / ("%s-%d.webp" % (plate["id"], w)))],
                           check=True)
    master.unlink()
    return im.size


# Written on every run and read by engine/preview.py: the browser positions
# text with the same numbers the crop was measured against.
CALIB = ROOT.parent / "engine" / "plates.json"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for p in PLATES:
        w, h = build(p)
        ppi = w / p["inches"]
        print("%-6s %-8s %-5s %4dx%-4d  %3din wide  %.1f px/in  "
              "3\" char = %.0fpx  %s"
              % (p["id"], p["view"], "dark" if p["dark"] else "light", w, h,
                 p["inches"], ppi, 3 * ppi, p["nominal"]))
    CALIB.write_text(json.dumps(
        [{k: v for k, v in p.items() if k != "crop"} for p in PLATES],
        indent=1) + "\n")
    print("\n%d plates -> public/assets/img/ + %s"
          % (len(PLATES), CALIB.relative_to(ROOT.parent)))


if __name__ == "__main__":
    main()
